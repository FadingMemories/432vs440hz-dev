let currentLanguage = 'en';

export function t(key) {
  return translations[currentLanguage]?.[key] || translations.en[key] || key;
}

export function getLanguage() {
  return currentLanguage;
}

export function setLanguage(language) {
  currentLanguage = language === 'es' ? 'es' : 'en';
  localStorage.setItem('language', currentLanguage);
  document.documentElement.lang = currentLanguage;
  applyTranslations();
  window.dispatchEvent(new CustomEvent('languagechange', { detail: { language: currentLanguage } }));
}

export function applyTranslations() {
  const isComparatorPage = Boolean(document.querySelector('[data-i18n="appTitle"]'));
  const isHemiPage = Boolean(document.querySelector('[data-i18n="hemiWaveTitle"]'));

  if (isComparatorPage) {
    document.title = t('pageTitle');
    document.querySelector('meta[name="description"]')?.setAttribute('content', t('pageDescription'));
    document.querySelector('meta[property="og:title"]')?.setAttribute('content', t('pageTitle'));
    document.querySelector('meta[property="og:description"]')?.setAttribute('content', t('pageDescription'));
    document.querySelector('meta[name="twitter:title"]')?.setAttribute('content', t('pageTitle'));
    document.querySelector('meta[name="twitter:description"]')?.setAttribute('content', t('pageDescription'));
  }

  if (isHemiPage) {
    document.title = t('hemiPageTitle');
    document.querySelector('meta[name="description"]')?.setAttribute('content', t('hemiPageDescription'));
    document.querySelector('meta[property="og:title"]')?.setAttribute('content', t('hemiPageTitle'));
    document.querySelector('meta[property="og:description"]')?.setAttribute('content', t('hemiPageDescription'));
    document.querySelector('meta[name="twitter:title"]')?.setAttribute('content', t('hemiPageTitle'));
    document.querySelector('meta[name="twitter:description"]')?.setAttribute('content', t('hemiPageDescription'));
  }

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });

  document.querySelectorAll('[data-language-switch]').forEach((button) => {
    button.classList.toggle('active', button.dataset.languageSwitch === currentLanguage);
    button.setAttribute('aria-pressed', String(button.dataset.languageSwitch === currentLanguage));
  });
}

export function initI18n() {
  const params = new URLSearchParams(window.location.search);
  const requestedLanguage = params.get('lang') || localStorage.getItem('language') || 'en';
  currentLanguage = requestedLanguage === 'es' ? 'es' : 'en';
  document.documentElement.lang = currentLanguage;
  applyTranslations();

  document.querySelectorAll('[data-language-switch]').forEach((button) => {
    button.addEventListener('click', () => setLanguage(button.dataset.languageSwitch));
  });
}
